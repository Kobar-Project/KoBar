import { describe, expect, it } from 'vitest';
import { MAC_CONCEALED_FORMATS, hasMacConcealedMarker, osClipboardMime } from '../electron/lib/clipboardGuards.cjs';

// MAC-018: pure type-list tests only, the clipboard API is never touched.
describe('hasMacConcealedMarker', () => {
    const utis = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType'];
    it.each(utis)('detects %s bare and wrapped', (uti) => {
        expect(hasMacConcealedMarker(['text/plain', uti])).toBe(true);
        expect(hasMacConcealedMarker(['text/plain', osClipboardMime(uti)])).toBe(true);
    });
    it('is case-insensitive', () => {
        expect(hasMacConcealedMarker(['ORG.NSPASTEBOARD.CONCEALEDTYPE'])).toBe(true);
        expect(hasMacConcealedMarker(['org.nspasteboard.concealedtype'])).toBe(true);
    });
    it('detects the 1Password marker', () => {
        expect(hasMacConcealedMarker(['com.agilebits.onepassword'])).toBe(true);
    });
    it('ignores unrelated types and empty lists', () => {
        expect(hasMacConcealedMarker(['text/plain', 'public.utf8-plain-text', 'org.nspasteboard.source', 'image/png'])).toBe(false);
        expect(hasMacConcealedMarker([])).toBe(false);
    });
    it('exports the three nspasteboard markers', () => {
        for (const uti of utis) expect(MAC_CONCEALED_FORMATS).toContain(uti);
    });
});
